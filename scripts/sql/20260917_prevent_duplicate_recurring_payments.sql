-- Prevent more than one active payment for a recurring series.
--
-- The Sport Center API writes sport_center.sport_payments directly.  The
-- trigger is the user-facing guard (it returns a stable 23505 error with a
-- useful message), while the unique index is the final database invariant.
-- The advisory transaction lock makes the pre-check safe when two requests
-- for the same series arrive concurrently.

BEGIN;

ALTER TABLE sport_center.sport_payments
  ADD COLUMN IF NOT EXISTS recurring_series_id text,
  ADD COLUMN IF NOT EXISTS group_id text,
  ADD COLUMN IF NOT EXISTS member_id text;

COMMENT ON COLUMN sport_center.sport_payments.recurring_series_id IS
  'Stable recurring payment series identifier; only one active payment may use a series.';
COMMENT ON COLUMN sport_center.sport_payments.group_id IS
  'Optional booking/group identifier supplied by the recurring payment source.';
COMMENT ON COLUMN sport_center.sport_payments.member_id IS
  'Optional member identifier supplied by the recurring payment source.';

CREATE TABLE IF NOT EXISTS sport_center.sport_payment_void_audits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id integer NOT NULL
    REFERENCES sport_center.sport_payments(id) ON DELETE RESTRICT,
  original_status text NOT NULL,
  recurring_series_id text,
  group_id text,
  member_id text,
  original_journal_id integer,
  reversal_journal_id integer,
  actor text NOT NULL,
  reason text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sport_payment_void_audits_payment_unique UNIQUE (payment_id)
);

CREATE INDEX IF NOT EXISTS sport_payment_void_audits_series_idx
  ON sport_center.sport_payment_void_audits (recurring_series_id)
  WHERE recurring_series_id IS NOT NULL;

CREATE OR REPLACE FUNCTION sport_center.prevent_duplicate_active_recurring_payment()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'sport_center'
AS $function$
DECLARE
  v_series text := NULLIF(btrim(NEW.recurring_series_id), '');
  v_existing_payment_id integer;
BEGIN
  IF v_series IS NULL
     OR NEW.status::text = 'rejected'
  THEN
    RETURN NEW;
  END IF;

  -- A transaction advisory lock serializes the check without locking the
  -- entire payment table. The unique index below remains the last-resort
  -- protection if another writer does not execute this trigger.
  PERFORM pg_advisory_xact_lock(hashtextextended(v_series, 0));

  SELECT p.id
    INTO v_existing_payment_id
    FROM sport_center.sport_payments p
   WHERE NULLIF(btrim(p.recurring_series_id), '') = v_series
     AND p.status::text <> 'rejected'
     AND p.id IS DISTINCT FROM NEW.id
   ORDER BY p.id
   LIMIT 1;

  IF v_existing_payment_id IS NOT NULL THEN
    RAISE EXCEPTION USING
      ERRCODE = '23505',
      CONSTRAINT = 'sport_payments_recurring_series_active_unique',
      MESSAGE = 'DUPLICATE_RECURRING_PAYMENT',
      DETAIL = format(
        'recurring_series_id=%s already has active payment id=%s',
        v_series,
        v_existing_payment_id
      ),
      HINT = 'Void and reverse the existing payment before creating a replacement.';
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_prevent_duplicate_active_recurring_payment
  ON sport_center.sport_payments;

CREATE TRIGGER trg_prevent_duplicate_active_recurring_payment
BEFORE INSERT OR UPDATE OF status, recurring_series_id
ON sport_center.sport_payments
FOR EACH ROW
EXECUTE FUNCTION sport_center.prevent_duplicate_active_recurring_payment();

DO $migration$
BEGIN
  IF EXISTS (
    SELECT 1
      FROM sport_center.sport_payments
     WHERE NULLIF(btrim(recurring_series_id), '') IS NOT NULL
       AND status <> 'rejected'
     GROUP BY NULLIF(btrim(recurring_series_id), '')
    HAVING COUNT(*) > 1
  ) THEN
    RAISE EXCEPTION
      'RECURRING_PAYMENT_DUPLICATES_MUST_BE_VOIDED_BEFORE_INDEX_CREATION';
  END IF;
END;
$migration$;

CREATE UNIQUE INDEX IF NOT EXISTS sport_payments_recurring_series_active_unique
  ON sport_center.sport_payments (NULLIF(btrim(recurring_series_id), ''))
  WHERE NULLIF(btrim(recurring_series_id), '') IS NOT NULL
    AND status <> 'rejected';

CREATE OR REPLACE FUNCTION sport_center.void_payment_for_recurring_replacement(
  p_payment_id integer,
  p_actor text,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'sport_center'
AS $function$
DECLARE
  v_payment sport_center.sport_payments%ROWTYPE;
  v_journal sport_center.accounting_journals%ROWTYPE;
  v_audit sport_center.sport_payment_void_audits%ROWTYPE;
  v_existing_audit jsonb;
  v_journal_count integer;
  v_source_line_count integer;
  v_reversal_line_count integer;
  v_reversal_id integer;
BEGIN
  IF NULLIF(btrim(p_actor), '') IS NULL
     OR NULLIF(btrim(p_reason), '') IS NULL
  THEN
    RAISE EXCEPTION
      'PAYMENT_VOID_ACTOR_AND_REASON_REQUIRED';
  END IF;

  SELECT to_jsonb(a)
    INTO v_existing_audit
    FROM sport_center.sport_payment_void_audits a
   WHERE a.payment_id = p_payment_id;

  IF v_existing_audit IS NOT NULL THEN
    RETURN v_existing_audit;
  END IF;

  SELECT *
    INTO v_payment
    FROM sport_center.sport_payments
   WHERE id = p_payment_id
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'PAYMENT_NOT_FOUND: %', p_payment_id;
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended(
      COALESCE(
        NULLIF(btrim(v_payment.recurring_series_id), ''),
        'payment:' || p_payment_id::text
      ),
      0
    )
  );

  IF v_payment.status::text = 'rejected' THEN
    RAISE EXCEPTION
      'PAYMENT_ALREADY_INACTIVE: payment=% status=%',
      p_payment_id,
      v_payment.status::text;
  END IF;

  SELECT COUNT(*)::integer
    INTO v_journal_count
    FROM sport_center.accounting_journals
   WHERE payment_id = p_payment_id
     AND journal_type = 'payment_confirmed'
     AND is_reversal = false
     AND status = 'posted';

  IF v_journal_count > 1 THEN
    RAISE EXCEPTION
      'PAYMENT_VOID_MULTIPLE_CANONICAL_JOURNALS: payment=% count=%',
      p_payment_id,
      v_journal_count;
  END IF;

  IF v_journal_count = 1 THEN
    SELECT *
      INTO v_journal
      FROM sport_center.accounting_journals
     WHERE payment_id = p_payment_id
       AND journal_type = 'payment_confirmed'
       AND is_reversal = false
       AND status = 'posted'
     ORDER BY id
     LIMIT 1
     FOR UPDATE;

    SELECT COUNT(*)::integer
      INTO v_source_line_count
      FROM sport_center.accounting_journal_lines
     WHERE journal_id = v_journal.id;

    IF v_source_line_count = 0 THEN
      RAISE EXCEPTION
        'PAYMENT_VOID_SOURCE_JOURNAL_HAS_NO_LINES: journal=%',
        v_journal.id;
    END IF;

    SELECT COUNT(*)::integer, MIN(id)
      INTO v_reversal_line_count, v_reversal_id
      FROM sport_center.accounting_journals
     WHERE reversal_of_id = v_journal.id
       AND is_reversal = true;

    IF v_reversal_line_count > 1 THEN
      RAISE EXCEPTION
        'PAYMENT_VOID_MULTIPLE_REVERSALS: journal=% count=%',
        v_journal.id,
        v_reversal_line_count;
    END IF;

    IF v_reversal_line_count = 1 THEN
      IF NOT EXISTS (
        SELECT 1
          FROM sport_center.accounting_journals
         WHERE id = v_reversal_id
           AND status = 'posted'
      ) THEN
        RAISE EXCEPTION
          'PAYMENT_VOID_EXISTING_REVERSAL_NOT_POSTED: journal=% reversal=%',
          v_journal.id,
          v_reversal_id;
      END IF;
    ELSE
      INSERT INTO sport_center.accounting_journals (
        booking_id,
        order_number,
        journal_type,
        debit_account,
        debit_amount,
        credit_revenue_account,
        credit_revenue_amount,
        credit_ppn_account,
        credit_ppn_amount,
        journal_date,
        is_reversal,
        reversal_of_id,
        notes,
        payment_id,
        payment_method,
        payment_provider,
        payment_type,
        bank_account_id,
        gross_amount,
        dpp_amount,
        tax_amount,
        provider_reference,
        provider_order_id,
        merchant_trade_no,
        provider_trade_no,
        status,
        company_id,
        created_by,
        approved_by,
        approved_at,
        posted_by,
        posted_at,
        source_schema,
        source_table,
        source_id,
        source_event_id,
        correlation_id,
        settlement_id,
        settlement_reference,
        settlement_date,
        settlement_batch_id,
        provider_name,
        provider_id,
        expected_settlement_date,
        settlement_status,
        mdr_rate,
        mdr_amount
      )
      SELECT
        j.booking_id,
        j.order_number,
        'reversal',
        j.debit_account,
        j.debit_amount,
        j.credit_revenue_account,
        j.credit_revenue_amount,
        j.credit_ppn_account,
        j.credit_ppn_amount,
        j.journal_date,
        true,
        j.id,
        format('Audited recurring payment void: %s', btrim(p_reason)),
        NULL,
        j.payment_method,
        j.payment_provider,
        j.payment_type,
        j.bank_account_id,
        j.gross_amount,
        j.dpp_amount,
        j.tax_amount,
        j.provider_reference,
        j.provider_order_id,
        j.merchant_trade_no,
        j.provider_trade_no,
        'posted',
        j.company_id,
        btrim(p_actor),
        btrim(p_actor),
        clock_timestamp(),
        btrim(p_actor),
        clock_timestamp(),
        j.source_schema,
        j.source_table,
        j.source_id,
        NULL,
        j.correlation_id,
        j.settlement_id,
        j.settlement_reference,
        j.settlement_date,
        j.settlement_batch_id,
        j.provider_name,
        j.provider_id,
        j.expected_settlement_date,
        j.settlement_status,
        j.mdr_rate,
        j.mdr_amount
        FROM sport_center.accounting_journals j
       WHERE j.id = v_journal.id
      RETURNING id INTO v_reversal_id;

      INSERT INTO sport_center.accounting_journal_lines (
        journal_id,
        line_type,
        account_code,
        account_name,
        amount,
        description
      )
      SELECT
        v_reversal_id,
        CASE line_type
          WHEN 'debit' THEN 'credit'
          WHEN 'credit' THEN 'debit'
          ELSE line_type
        END,
        account_code,
        account_name,
        amount,
        format('Audited reversal of journal #%s', v_journal.id)
        FROM sport_center.accounting_journal_lines
       WHERE journal_id = v_journal.id;

      SELECT COUNT(*)::integer
        INTO v_reversal_line_count
        FROM sport_center.accounting_journal_lines
       WHERE journal_id = v_reversal_id;

      IF v_reversal_line_count <> v_source_line_count THEN
        RAISE EXCEPTION
          'PAYMENT_VOID_REVERSAL_LINE_COUNT_MISMATCH: journal=% reversal=%',
          v_journal.id,
          v_reversal_id;
      END IF;
    END IF;
  END IF;

  -- Draft journals are not accounting history yet. Void them rather than
  -- deleting them, so the replacement draft can be created safely.
  UPDATE sport_center.accounting_journals
     SET status = 'voided',
         voided_by = btrim(p_actor),
         voided_at = clock_timestamp(),
         updated_at = clock_timestamp()
   WHERE payment_id = p_payment_id
     AND journal_type = 'payment_confirmed'
     AND is_reversal = false
     AND status = 'draft';

  UPDATE sport_center.sport_payments
     SET status = 'rejected',
         updated_at = clock_timestamp()
   WHERE id = p_payment_id;

  INSERT INTO sport_center.sport_payment_void_audits (
    payment_id,
    original_status,
    recurring_series_id,
    group_id,
    member_id,
    original_journal_id,
    reversal_journal_id,
    actor,
    reason
  )
  VALUES (
    p_payment_id,
    v_payment.status::text,
    v_payment.recurring_series_id,
    v_payment.group_id,
    v_payment.member_id,
    NULLIF(v_journal.id, 0),
    NULLIF(v_reversal_id, 0),
    btrim(p_actor),
    btrim(p_reason)
  )
  RETURNING id INTO v_audit.id;

  SELECT to_jsonb(a)
    INTO v_existing_audit
    FROM sport_center.sport_payment_void_audits a
   WHERE a.id = v_audit.id;

  RETURN v_existing_audit;
END;
$function$;

COMMIT;