-- The reduced fixtures used literal IDs; production writers obtain serial IDs.
do $$
declare relation_name text;
begin
  foreach relation_name in array array[
    'bank_mutations', 'bank_reconciliation_matches', 'payment_matching_groups',
    'payment_allocations', 'accounting_entries', 'accounting_entry_lines',
    'company_bank_accounts', 'chart_of_accounts'
  ] loop
    if not exists (
      select 1 from information_schema.columns
      where table_schema = 'public' and table_name = relation_name
        and column_name = 'id' and is_identity = 'YES'
    ) then
      execute format('alter table public.%I alter column id add generated by default as identity', relation_name);
    end if;
  end loop;
end $$;

