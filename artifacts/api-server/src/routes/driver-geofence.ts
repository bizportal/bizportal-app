import { Router } from "express";
import { getDevSession, getProductionSession, getProductionUser, isDevelopmentEnvironment } from "./dev-auth";

const router = Router();

async function requireBizPortalUser(req: any, res: any, next: any) {
  try {
    if (isDevelopmentEnvironment()) {
      if (!getDevSession(req)?.email) {
        res.status(401).json({ error: "Unauthorized" });
        return;
      }
    } else {
      const session = getProductionSession(req);
      if (!session || !(await getProductionUser(session))) {
        res.status(401).json({ error: "Unauthorized" });
        return;
      }
    }
    next();
  } catch (error) {
    req.log?.error?.({ error }, "Driver geofence authorization failed");
    res.status(503).json({ error: "Authorization service unavailable." });
  }
}

// Geofence alerts are generated by the driver runtime. The standalone BizPortal
// must not depend on CST-SUPER-APP's in-memory alert store. Until a persistent
// shared alert source is introduced, return an authenticated empty projection
// instead of a misleading 404 from a legacy frontend contract.
router.get("/drivers/geofence-alerts", requireBizPortalUser, (_req, res) => {
  res.json([]);
});

router.post("/drivers/geofence-alerts/:id/resolve", requireBizPortalUser, (_req, res) => {
  res.status(404).json({ error: "Alert not found or already resolved" });
});

export default router;
