import {afterAll,beforeAll,beforeEach,describe,expect,it,vi} from "vitest";
import express from "express";
import {once} from "node:events";
import {createServer} from "node:http";
import {createRequire} from "node:module";

const state=vi.hoisted(()=>({role:"super_admin",dedicated:null as any,shared:0}));
vi.mock("../routes/dev-auth",()=>({
  isDevelopmentEnvironment:()=>process.env.APP_ENV==="development",
  getProductionSession:()=>null,getProductionUser:async()=>null,
  getDevSession:()=>state.role?{id:"fixture",email:"fixture@example.invalid",role:state.role,companyId:1}:null,
}));
vi.mock("@workspace/db",()=>({
  pool:{connect:async()=>{state.shared++;throw Error("SHARED_POOL_FORBIDDEN");},
    query:async()=>{state.shared++;throw Error("SHARED_POOL_FORBIDDEN");}},
  createDedicatedPayrollPool:()=>state.dedicated,
}));

const url=process.env.CASH_QA_PG_URL;
const suite=url?describe:describe.skip;
suite("DEV Payroll seven-component HTTP routes on disposable PostgreSQL",()=>{
  let admin:any, db:any, reader:any;
  let databaseCreated=false, roleCreated=false;
  const fixture={baseSalary:"5000000",allowance:"100000",bpjsJhtEmployee:"100000",
    bpjsKesEmployee:"50000",pph21:"0",otherDeductions:"0",kasbonDeduction:"0",
    effectiveFrom:"2026-11-01",notes:"Synthetic HR confirmation",confirm:true};
  beforeAll(async()=>{
    const u=new URL(url!);
    if(u.protocol!=="postgresql:"||u.hostname!=="127.0.0.1"||u.port!=="55432"||
      u.pathname!=="/cash_qa"||u.username!=="cash_qa")throw Error("DISPOSABLE_DATABASE_REQUIRED");
    const {Pool}=createRequire(import.meta.url)("pg");
    admin=new Pool({connectionString:url,max:1,connectionTimeoutMillis:3000});
    await admin.query("CREATE DATABASE payroll_components_qa");
    databaseCreated=true;
    await admin.query("CREATE ROLE payroll_components_qa_reader LOGIN NOSUPERUSER NOBYPASSRLS PASSWORD 'fixture_ci_only'");
    roleCreated=true;
    u.pathname="/payroll_components_qa";
    db=new Pool({connectionString:u.toString(),max:2,connectionTimeoutMillis:3000});
    await db.query(`
      CREATE TABLE public.employees(id integer PRIMARY KEY,company_id integer NOT NULL,
        first_name text,last_name text,salary real,status text NOT NULL,deleted_at timestamptz);
      CREATE TABLE public.payroll_salary_profiles(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        company_id bigint NOT NULL,employee_id bigint NOT NULL REFERENCES public.employees(id),
        effective_from date NOT NULL,base_salary numeric(14,2) NOT NULL,allowance numeric(14,2) NOT NULL,
        notes text,updated_at timestamptz DEFAULT now(),UNIQUE(company_id,employee_id,effective_from));
      CREATE TABLE public.payroll_deduction_settings(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        company_id bigint NOT NULL,employee_id bigint NOT NULL REFERENCES public.employees(id),
        effective_from date NOT NULL,code text NOT NULL,amount numeric(14,2) NOT NULL,notes text,
        updated_at timestamptz DEFAULT now(),UNIQUE(company_id,employee_id,effective_from,code));
      CREATE TABLE public.payroll_items(id int PRIMARY KEY);
      CREATE TABLE public.accounting_entries(id int PRIMARY KEY);
      CREATE TABLE public.cash_advances(id int PRIMARY KEY);
      ALTER TABLE public.employees ENABLE ROW LEVEL SECURITY;
      ALTER TABLE public.payroll_salary_profiles ENABLE ROW LEVEL SECURITY;
      ALTER TABLE public.payroll_deduction_settings ENABLE ROW LEVEL SECURITY;
      CREATE POLICY qa_roster ON public.employees FOR SELECT TO payroll_components_qa_reader
        USING(company_id=NULLIF(current_setting('app.payroll_company_id',true),'')::integer);
      CREATE POLICY qa_salary ON public.payroll_salary_profiles FOR ALL TO payroll_components_qa_reader
        USING(company_id::text=current_setting('app.payroll_company_id',true))
        WITH CHECK(company_id::text=current_setting('app.payroll_company_id',true));
      CREATE POLICY qa_deductions ON public.payroll_deduction_settings FOR ALL TO payroll_components_qa_reader
        USING(company_id::text=current_setting('app.payroll_company_id',true))
        WITH CHECK(company_id::text=current_setting('app.payroll_company_id',true));
      GRANT USAGE ON SCHEMA public TO payroll_components_qa_reader;
      GRANT SELECT(id,company_id,first_name,last_name,salary,status,deleted_at) ON public.employees TO payroll_components_qa_reader;
      GRANT SELECT,INSERT,UPDATE ON public.payroll_salary_profiles,public.payroll_deduction_settings TO payroll_components_qa_reader;
      GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO payroll_components_qa_reader;
      INSERT INTO public.employees VALUES
        (21,1,'Synthetic','One',5000000,'active',NULL),
        (22,2,'Synthetic','Two',6000000,'active',NULL),
        (23,1,'Synthetic','Inactive',7000000,'inactive',NULL);
      CREATE FUNCTION public.qa_reject_pph() RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN
        IF NEW.notes='Synthetic forced failure' AND NEW.code='pph21' THEN
          RAISE EXCEPTION 'QA_DEDUCTION_FAILURE';
        END IF;
        RETURN NEW;
      END $$;
      CREATE TRIGGER qa_reject_pph BEFORE INSERT OR UPDATE ON public.payroll_deduction_settings
        FOR EACH ROW EXECUTE FUNCTION public.qa_reject_pph();
    `);
    u.username="payroll_components_qa_reader";u.password="fixture_ci_only";
    reader=new Pool({connectionString:u.toString(),max:2,connectionTimeoutMillis:3000});
    state.dedicated=reader;
    vi.stubEnv("APP_ENV","development");
    // Actual route uses its dedicated pool and company scope, only the factory
    // is redirected to a disposable localhost database with a restricted role.
    vi.stubEnv("PAYROLL_DATABASE_URL_DEV","postgresql://bizportal_payroll_dev.xssrfshdrtdfupgqwfdw:fixture@127.0.0.1:65432/payroll_ci");
  },20000);
  beforeEach(async()=>{
    state.role="super_admin";state.shared=0;
    vi.stubEnv("PAYROLL_DEV_COMPONENTS_ENABLED","true");
    await db.query("TRUNCATE public.payroll_salary_profiles,public.payroll_deduction_settings");
  });
  afterAll(async()=>{
    try{
      if(reader)await reader.end();
      if(db)await db.end();
      if(databaseCreated)await admin.query("DROP DATABASE payroll_components_qa");
      if(roleCreated)await admin.query("DROP ROLE payroll_components_qa_reader");
    }finally{if(admin)await admin.end();vi.unstubAllEnvs();}
  });
  async function request(path:string,method="GET",body?:unknown){
    const {default:router}=await import("../routes/payroll");
    const app=express();app.use(express.json());app.use("/api",router);
    const server=createServer(app);server.listen(0,"127.0.0.1");await once(server,"listening");
    const address=server.address();
    if(!address||typeof address==="string")throw Error("NO_TEST_SERVER");
    try{
      const r=await fetch("http://127.0.0.1:"+address.port+"/api/payroll/"+path,
        {method,headers:{"Content-Type":"application/json"},body:body===undefined?undefined:JSON.stringify(body)});
      return {status:r.status,data:await r.json()};
    }finally{await new Promise<void>((resolve,reject)=>server.close(e=>e?reject(e):resolve()));}
  }
  async function counts(){
    return (await db.query(`SELECT
      (SELECT count(*)::int FROM public.payroll_salary_profiles) profiles,
      (SELECT count(*)::int FROM public.payroll_deduction_settings) deductions,
      (SELECT count(*)::int FROM public.payroll_items) items,
      (SELECT count(*)::int FROM public.accounting_entries) journals,
      (SELECT count(*)::int FROM public.cash_advances) advances`)).rows[0];
  }
  const save=(body:unknown=fixture,company=1,id=21)=>request("components/"+id+"?companyId="+company,"PUT",body);
  const read=(date:string)=>request("components/21?companyId=1&effectiveFrom="+date);
  it("saves seven components atomically, then reads exact date without touching financial records",async()=>{
    expect((await save()).data).toMatchObject({componentsSaved:7,gross:"5100000.00",deductions:"150000.00",net:"4950000.00",
      appliedToPayroll:false,posted:false,paid:false,settledKasbon:false});
    const r=await read("2026-11-01");
    expect(r.status).toBe(200);
    expect(r.data).toMatchObject({companyId:1,employeeId:21,effectiveFrom:"2026-11-01",complete:true,
      values:{baseSalary:"5000000.00",allowance:"100000.00",bpjsJhtEmployee:"100000.00",bpjsKesEmployee:"50000.00",
        pph21:"0.00",otherDeductions:"0.00",kasbonDeduction:"0.00"},summary:{net:"4950000.00"}});
    expect(await counts()).toEqual({profiles:1,deductions:5,items:0,journals:0,advances:0});
    expect(state.shared).toBe(0);
  });
  it("keeps distinct effective dates and replay does not duplicate settings",async()=>{
    expect((await save()).status).toBe(200);
    expect((await save({...fixture,baseSalary:"6000000",effectiveFrom:"2026-12-01"})).status).toBe(200);
    expect((await save()).status).toBe(200);
    expect((await read("2026-11-01")).data.values.baseSalary).toBe("5000000.00");
    expect((await read("2026-12-01")).data.values.baseSalary).toBe("6000000.00");
    expect((await request("components/21?companyId=1")).data.effectiveFrom).toBe("2026-12-01");
    expect(await counts()).toEqual({profiles:2,deductions:10,items:0,journals:0,advances:0});
  });
  it("rolls back profile and every deduction when a later deduction fails",async()=>{
    expect((await save({...fixture,notes:"Synthetic forced failure"})).status).toBe(503);
    expect(await counts()).toEqual({profiles:0,deductions:0,items:0,journals:0,advances:0});
    expect((await save()).status).toBe(200);
    expect((await save({...fixture,baseSalary:"8000000",notes:"Synthetic forced failure"})).status).toBe(503);
    expect((await read("2026-11-01")).data.values.baseSalary).toBe("5000000.00");
    expect(await counts()).toEqual({profiles:1,deductions:5,items:0,journals:0,advances:0});
  });
  it("enforces app authorization, tenant and inactive-employee rejection",async()=>{
    state.role="finance";expect((await save()).status).toBe(403);
    state.role="";expect((await save()).status).toBe(401);
    state.role="super_admin";expect((await save(fixture,2,21)).status).toBe(404);
    expect((await save(fixture,1,23)).status).toBe(404);
    expect((await save({...fixture,kasbonDeduction:"100"})).status).toBe(409);
    vi.stubEnv("PAYROLL_DEV_COMPONENTS_ENABLED","");expect((await save()).status).toBe(501);
    expect(await counts()).toEqual({profiles:0,deductions:0,items:0,journals:0,advances:0});
    expect(state.shared).toBe(0);
  });
  it("proves restricted PostgreSQL login, RLS scope and scope reset",async()=>{
    expect((await save()).status).toBe(200);
    expect((await save(fixture,2,22)).status).toBe(200);
    const c=await reader.connect();
    try{
      const role=(await c.query("SELECT rolsuper,rolbypassrls FROM pg_roles WHERE rolname=current_user")).rows[0];
      expect(role).toEqual({rolsuper:false,rolbypassrls:false});
      expect((await c.query("SELECT company_id FROM public.payroll_salary_profiles")).rows).toEqual([]);
      await c.query("BEGIN");
      await c.query("SELECT set_config('app.payroll_company_id','1',true)");
      expect((await c.query("SELECT company_id::int FROM public.payroll_salary_profiles")).rows).toEqual([{company_id:1}]);
      await expect(c.query("INSERT INTO public.payroll_salary_profiles(company_id,employee_id,effective_from,base_salary,allowance) VALUES(2,22,'2026-10-01',1,0)")).rejects.toMatchObject({code:"42501"});
      await c.query("ROLLBACK");
      expect((await c.query("SELECT company_id FROM public.payroll_salary_profiles")).rows).toEqual([]);
    }finally{await c.query("ROLLBACK");c.release();}
    expect(await counts()).toEqual({profiles:2,deductions:10,items:0,journals:0,advances:0});
  });
});
